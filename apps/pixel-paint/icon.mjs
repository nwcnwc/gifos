// Procedural Pixel Paint icon: a dark rounded card holding a 16×16 NES
// mushroom that is painted in, pixel by pixel. Super-sample → box-downsample
// → small palette; deterministic so GIF builds reproduce.
import { deflateSync } from 'node:zlib';

const OUT = 128, SS = 3, RW = OUT * SS, FRAMES = 12;

const CARD_A = [28, 30, 38];
const CARD_B = [16, 18, 24];
const CHECK_L = [255, 255, 255];
const CHECK_D = [203, 203, 203];
const INK = [10, 10, 14];
const RED = [248, 56, 0];
const RED_D = [168, 16, 0];
const CREAM = [252, 228, 168];
const WHITE = [252, 252, 252];
const STEM = [232, 168, 80];
const STEM_D = [172, 108, 32];
const CYAN = [60, 188, 252];

function mix(a, b, t) { return [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t]; }
function inCard(x, y, m, r) {
  const lo = m, hi = OUT - m;
  if (x < lo || x > hi || y < lo || y > hi) return false;
  const cx = Math.min(Math.max(x, lo + r), hi - r), cy = Math.min(Math.max(y, lo + r), hi - r);
  if (x >= lo + r && x <= hi - r) return true;
  if (y >= lo + r && y <= hi - r) return true;
  const dx = x - cx, dy = y - cy; return dx * dx + dy * dy <= r * r;
}
function buildPalette() {
  const pal = [[0, 0, 0]];
  for (const b of [CARD_A, CARD_B, CHECK_L, CHECK_D, INK, RED, RED_D, CREAM, WHITE, STEM, STEM_D, CYAN]) {
    for (let s = 0; s <= 3; s++) pal.push(mix(b, [255, 255, 255], s * 0.1).map(Math.round));
    pal.push(mix(b, [0, 0, 0], 0.28).map(Math.round));
  }
  return pal.slice(0, 64);
}
function nearest(pal, r, g, b) {
  let bi = 1, bd = 1e9;
  for (let i = 1; i < pal.length; i++) {
    const p = pal[i], dr = p[0] - r, dg = p[1] - g, db = p[2] - b, d = dr * dr + dg * dg + db * db;
    if (d < bd) { bd = d; bi = i; }
  }
  return bi;
}

// 16×16 mushroom. . empty, K ink, R red, D dark red, W white, C cream, S stem, T stem dark
const SPRITE = [
  '................',
  '......KKKK......',
  '....KKRRRRKK....',
  '...KRRRRRRRRK...',
  '..KRRWWRRRRRRK..',
  '..KRRRRRRWWRRK..',
  '.KRRRRRRRRRRRRK.',
  '.KRRWWRRRRRRRRK.',
  '.KKRRRRRRRRRRKK.',
  '...KKKKKKKKKK...',
  '....KSSSSSSK....',
  '....KSSCCSSK....',
  '....KSSKKSSK....',
  '....KSSSSSSK....',
  '.....KKKKKK.....',
  '................',
];
const SPRITE_COL = {
  K: INK, R: RED, D: RED_D, W: WHITE, C: CREAM, S: STEM, T: STEM_D,
};

function frameIndices(pal, f) {
  const rgba = new Float32Array(RW * RW * 4);
  const m = 8, rad = 22;
  const painted = Math.floor(((f + 1) / FRAMES) * 16);
  const ox = 32, oy = 28, cell = 4;
  for (let py = 0; py < RW; py++) for (let px = 0; px < RW; px++) {
    const x = px / SS, y = py / SS;
    let col = null, a = 0;
    if (inCard(x, y, m, rad)) {
      a = 1;
      col = mix(CARD_A, CARD_B, Math.max(0, Math.min(1, (y - m) / (OUT - 2 * m))));
      const gx = (x - ox) / cell, gy = (y - oy) / cell;
      if (gx >= 0 && gx < 16 && gy >= 0 && gy < 16) {
        const ix = gx | 0, iy = gy | 0;
        const checker = ((ix + iy) & 1) ? CHECK_D : CHECK_L;
        col = mix(checker, CARD_A, 0.08);
        if (iy < painted) {
          const ch = SPRITE[iy][ix];
          if (ch && SPRITE_COL[ch]) col = SPRITE_COL[ch];
        }
      }
    }
    const o = (py * RW + px) * 4;
    if (a) { rgba[o] = col[0]; rgba[o + 1] = col[1]; rgba[o + 2] = col[2]; rgba[o + 3] = 1; }
  }

  const idx = new Uint8Array(OUT * OUT);
  for (let y = 0; y < OUT; y++) for (let x = 0; x < OUT; x++) {
    let r = 0, g = 0, b = 0, aa = 0, n = SS * SS;
    for (let sy = 0; sy < SS; sy++) for (let sx = 0; sx < SS; sx++) {
      const o = (((y * SS + sy) * RW) + (x * SS + sx)) * 4;
      r += rgba[o]; g += rgba[o + 1]; b += rgba[o + 2]; aa += rgba[o + 3];
    }
    if (aa / n < 0.5) { idx[y * OUT + x] = 0; continue; }
    idx[y * OUT + x] = nearest(pal, r / n, g / n, b / n);
  }
  return idx;
}

export function pixelPaintIcon() {
  const pal = buildPalette();
  const frames = [];
  for (let f = 0; f < FRAMES; f++) frames.push(frameIndices(pal, f));
  const CT = 64;
  const flat = new Array(CT * 3).fill(0);
  for (let i = 0; i < pal.length && i < CT; i++) {
    flat[i * 3] = pal[i][0] | 0; flat[i * 3 + 1] = pal[i][1] | 0; flat[i * 3 + 2] = pal[i][2] | 0;
  }
  return { width: OUT, height: OUT, palette: flat, numColors: CT, minCodeSize: 6, frames, delayCs: 10, transparentIndex: 0 };
}

function crc(buf) {
  let c = ~0;
  for (let i = 0; i < buf.length; i++) {
    c ^= buf[i];
    for (let k = 0; k < 8; k++) c = (c >>> 1) ^ (0xedb88320 & -(c & 1));
  }
  return (~c) >>> 0;
}
function pngChunk(tag, data) {
  const t = Buffer.from(tag);
  const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
  const body = Buffer.concat([t, data]);
  const c = Buffer.alloc(4); c.writeUInt32BE(crc(body));
  return Buffer.concat([len, body, c]);
}

