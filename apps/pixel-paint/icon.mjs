function drawText(put, x, y, str, s, r, g, b) {
  let cx = x;
  for (const ch of String(str).toUpperCase()) {
    const gph = GLYPHS[ch];
    if (!gph) { cx += 6 * s; continue; }
    for (let row = 0; row < 7; row++) for (let col = 0; col < 5; col++) {
      if (gph[row] & (1 << (4 - col))) {
        for (let dy = 0; dy < s; dy++) for (let dx = 0; dx < s; dx++) {
          put(cx + col * s + dx, y + row * s + dy, r, g, b);
        }
      }
    }
    cx += 6 * s;
  }
}

export function screenshotPng() {
  const W = 1200, H = 720;
  const rgba = Buffer.alloc(W * H * 4, 0);
  const put = (x, y, r, g, b, a) => {
    if (x < 0 || y < 0 || x >= W || y >= H) return;
    const o = (y * W + x) * 4;
    rgba[o] = r; rgba[o + 1] = g; rgba[o + 2] = b; rgba[o + 3] = a == null ? 255 : a;
  };
  const fill = (x0, y0, x1, y1, r, g, b) => {
    x0 = Math.max(0, x0 | 0); y0 = Math.max(0, y0 | 0);
    x1 = Math.min(W, x1 | 0); y1 = Math.min(H, y1 | 0);
    for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) put(x, y, r, g, b);
  };

  fill(0, 0, W, H, 22, 22, 28);
  for (let y = 0; y < H; y++) {
    const t = y / H;
    const c = mix([28, 30, 38], [16, 18, 24], t);
    for (let x = 0; x < W; x++) put(x, y, c[0], c[1], c[2]);
  }

  drawText(put, 48, 48, 'PIXEL PAINT', 10, 60, 188, 252);
  drawText(put, 48, 140, 'A TINY 32 X 32', 4, 220, 220, 228);
  drawText(put, 48, 190, 'SPRITE CANVAS', 4, 220, 220, 228);
  fill(48, 250, 360, 302, 60, 188, 252);
  drawText(put, 64, 262, 'DRAW TOGETHER', 3, 16, 18, 24);
  drawText(put, 48, 330, 'PENCIL FILL ERASER', 3, 180, 180, 188);
  drawText(put, 48, 380, 'NES AND GAME BOY', 3, 248, 56, 0);
  drawText(put, 48, 640, 'UNOFFICIAL PORT', 3, 120, 120, 128);

  const cell = 28;
  const ox = 720, oy = 120;
  const n = 16;
  for (let iy = 0; iy < n; iy++) for (let ix = 0; ix < n; ix++) {
    const x0 = ox + ix * cell, y0 = oy + iy * cell;
    const ch = SPRITE[iy][ix];
    let col = ((ix + iy) & 1) ? CHECK_D : CHECK_L;
    if (ch && SPRITE_COL[ch]) col = SPRITE_COL[ch];
    fill(x0, y0, x0 + cell, y0 + cell, col[0], col[1], col[2]);
  }

  const raw = Buffer.alloc((W * 4 + 1) * H);
  for (let y = 0; y < H; y++) {
    raw[y * (W * 4 + 1)] = 0;
    rgba.copy(raw, y * (W * 4 + 1) + 1, y * W * 4, (y + 1) * W * 4);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(W, 0); ihdr.writeUInt32BE(H, 4);
  ihdr[8] = 8; ihdr[9] = 6; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    pngChunk('IHDR', ihdr),
    pngChunk('IDAT', deflateSync(raw, { level: 9 })),
    pngChunk('IEND', Buffer.alloc(0)),
  ]);
}
