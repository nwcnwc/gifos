function drawText(put, x, y, str, s, r, g, b) {
  let cx = x;
  for (const ch of String(str).toUpperCase()) {
    const gph = GLYPHS[ch];
    if (!gph) { cx += 6 * s; continue; }
    for (let row = 0; row < 7; row++) for (let col = 0; col < 5; col++) {
      if (gph[row] & (1 << (4 - col))) {
        for (let dy = 0; dy < s; dy++) for (let dx = 0; dx < s; dx++) {
          put(cx + col * s + dx, y + row * s + dy, r, g, b);
        }
      }
    }
    cx += 6 * s;
  }
}

export function screenshotPng() {
  const W = 1200, H = 720;
  const rgba = Buffer.alloc(W * H * 4, 0);
  const put = (x, y, r, g, b, a) => {
    x = x | 0; y = y | 0;
    if (x < 0 || y < 0 || x >= W || y >= H) return;
    const o = (y * W + x) * 4;
    rgba[o] = r; rgba[o + 1] = g; rgba[o + 2] = b; rgba[o + 3] = a == null ? 255 : a;
  };
  const fill = (x0, y0, x1, y1, r, g, b) => {
    x0 = Math.max(0, x0 | 0); y0 = Math.max(0, y0 | 0);
    x1 = Math.min(W, x1 | 0); y1 = Math.min(H, y1 | 0);
    for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) put(x, y, r, g, b);
  };
  const disk = (cx, cy, rad, r, g, b) => {
    const x0 = Math.max(0, (cx - rad) | 0), y0 = Math.max(0, (cy - rad) | 0);
    const x1 = Math.min(W, (cx + rad + 1) | 0), y1 = Math.min(H, (cy + rad + 1) | 0);
    for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) {
      const dx = x - cx, dy = y - cy;
      if (dx * dx + dy * dy <= rad * rad) put(x, y, r, g, b);
    }
  };

  fill(0, 0, W / 2, H, 255, 255, 255);
  fill(W / 2, 0, W, H, 28, 28, 32);

  drawText(put, 64, 48, 'CONTRAST RATIO', 6, 28, 28, 32);
  drawText(put, 64, 112, 'CHECK TEXT CONTRAST', 3, 80, 80, 86);
  drawText(put, 64, 160, 'BIGGER IS EASIER TO READ', 3, 80, 80, 86);

  drawText(put, 64, 240, 'BACKGROUND', 3, 120, 120, 128);
  drawText(put, 64, 280, 'WHITE', 4, 28, 28, 32);
  drawText(put, 700, 240, 'TEXT COLOR', 3, 180, 180, 186);
  drawText(put, 700, 280, 'BLACK 70%', 4, 248, 248, 246);

  disk(600, 430, 118, 94, 167, 42);
  disk(600, 430, 110, 88, 158, 38);
  drawText(put, 528, 400, '8.52', 6, 255, 255, 255);

  drawText(put, 64, 560, 'PASSES FOR ORDINARY TEXT', 3, 28, 28, 32);
  drawText(put, 700, 560, 'UNOFFICIAL PORT', 3, 180, 180, 186);
  drawText(put, 64, 640, 'LAST PAIR STAYS ON THIS DEVICE', 3, 80, 80, 86);

  const raw = Buffer.alloc((W * 4 + 1) * H);
  for (let y = 0; y < H; y++) {
    raw[y * (W * 4 + 1)] = 0;
    rgba.copy(raw, y * (W * 4 + 1) + 1, y * W * 4, (y + 1) * W * 4);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(W, 0); ihdr.writeUInt32BE(H, 4);
  ihdr[8] = 8; ihdr[9] = 6; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    pngChunk('IHDR', ihdr),
    pngChunk('IDAT', deflateSync(raw, { level: 9 })),
    pngChunk('IEND', Buffer.alloc(0)),
  ]);
}
