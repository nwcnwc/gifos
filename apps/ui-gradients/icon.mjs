function drawText(put, x, y, str, s, r, g, b) {
  let cx = x;
  for (const ch of String(str).toUpperCase()) {
    const gph = GLYPHS[ch];
    if (!gph) { cx += 6 * s; continue; }
    for (let row = 0; row < 7; row++) for (let col = 0; col < 5; col++) {
      if (gph[row] & (1 << (4 - col))) {
        for (let dy = 0; dy < s; dy++) for (let dx = 0; dx < s; dx++) {
          put(cx + col * s + dx, y + row * s + dy, r, g, b);
        }
      }
    }
    cx += 6 * s;
  }
}

export function screenshotPng() {
  const W = 1200, H = 720;
  const rgba = Buffer.alloc(W * H * 4, 0);
  const put = (x, y, r, g, b, a) => {
    x = x | 0; y = y | 0;
    if (x < 0 || y < 0 || x >= W || y >= H) return;
    const o = (y * W + x) * 4;
    rgba[o] = r; rgba[o + 1] = g; rgba[o + 2] = b; rgba[o + 3] = a == null ? 255 : a;
  };
  const fill = (x0, y0, x1, y1, r, g, b) => {
    x0 = Math.max(0, x0 | 0); y0 = Math.max(0, y0 | 0);
    x1 = Math.min(W, x1 | 0); y1 = Math.min(H, y1 | 0);
    for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) put(x, y, r, g, b);
  };
  const rr = (x0, y0, x1, y1, rad, r, g, b) => {
    for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) {
      const cx = Math.min(Math.max(x, x0 + rad), x1 - rad - 1);
      const cy = Math.min(Math.max(y, y0 + rad), y1 - rad - 1);
      if ((x - cx) * (x - cx) + (y - cy) * (y - cy) <= rad * rad) put(x, y, r, g, b);
    }
  };

  // Bloody Mary across the cover.
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    const col = mix(ORANGE, PINK, x / (W - 1));
    put(x, y, col[0], col[1], col[2]);
  }

  drawText(put, 48, 48, 'UIGRADIENTS', 7, 255, 255, 255);
  drawText(put, 48, 118, 'COPY A RAMP', 4, 255, 232, 240);
  rr(48, 190, 360, 258, 8, 221, 36, 118);
  drawText(put, 64, 212, 'SHARE THIS PICK', 3, 255, 255, 255);
  rr(48, 278, 280, 340, 8, 255, 255, 255);
  drawText(put, 64, 298, 'FAVOURITE', 3, 221, 36, 118);

  drawText(put, 48, 380, 'BLOODY MARY', 4, 255, 255, 255);
  rr(48, 450, 120, 522, 18, 255, 81, 47);
  rr(140, 450, 212, 522, 18, 221, 36, 118);
  drawText(put, 48, 548, 'HEARTS STAY HERE', 3, 255, 232, 240);
  drawText(put, 48, 600, 'THEY SEE THE PICK', 3, 255, 255, 255);

  rr(430, 40, 1160, 680, 16, 0, 0, 0);
  for (let y = 56; y < 664; y++) for (let x = 446; x < 1144; x++) {
    const col = mix(ORANGE, PINK, (x - 446) / (1144 - 446));
    put(x, y, col[0], col[1], col[2]);
  }
  drawText(put, 520, 330, 'BLOODY MARY', 5, 255, 255, 255);

  const raw = Buffer.alloc((W * 4 + 1) * H);
  for (let y = 0; y < H; y++) {
    raw[y * (W * 4 + 1)] = 0;
    rgba.copy(raw, y * (W * 4 + 1) + 1, y * W * 4, (y + 1) * W * 4);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(W, 0); ihdr.writeUInt32BE(H, 4);
  ihdr[8] = 8; ihdr[9] = 6; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    pngChunk('IHDR', ihdr),
    pngChunk('IDAT', deflateSync(raw, { level: 9 })),
    pngChunk('IEND', Buffer.alloc(0)),
  ]);
}
